// Workspace and configuration. A workspace is one folder with bughunterr.json and everything a hunt produces:
//   bughunterr.json   what to test: url, source code, spec (PRD), accounts, database, how to start the app
//   bugs/<ID>.json    one bug per file (schemas/bug.schema.json)
//   repro/<ID>.repro.mjs   captioned replay of the bug → videos/<ID>-<slug>.webm
//   specs/<ID>.spec.mjs    regression spec of the CORRECT behaviour, wrapped in knownBug('<ID>')
//   sessions/<run>/   notes, rules or inferred spec, agent log, app log, status.json
//   board/index.html  everything on one page
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONFIG_FILE = 'bughunterr.json';
export const DIRS = ['bugs', 'repro', 'specs', 'videos', 'sessions', 'board'];

export class BhError extends Error {}

export function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

export function writeJson(file, value) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(value, null, 2) + '\n');
}

export function appendJsonl(file, value) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(value) + '\n', { flag: 'a' });
}

export function listDir(dir, filter = () => true) {
  return existsSync(dir) ? readdirSync(dir).filter(filter).sort() : [];
}

// Finds the workspace: --dir, then BH_DIR, then the current folder or the nearest parent with bughunterr.json.
export function findWorkspace(dir) {
  const start = resolve(dir || process.env.BH_DIR || '.');
  for (let d = start; ; d = dirname(d)) {
    if (existsSync(join(d, CONFIG_FILE))) return d;
    if (dirname(d) === d) break;
  }
  if (dir || process.env.BH_DIR) throw new BhError(`no ${CONFIG_FILE} in ${start}. Run "bughunterr init" there first.`);
  throw new BhError(`no ${CONFIG_FILE} here or in a parent folder. Run "bughunterr init" first, or pass --dir.`);
}

// "$NAME" reads an environment variable, so passwords never have to live in the file.
export function secret(value, what) {
  if (typeof value !== 'string' || !value.startsWith('$')) return value;
  const v = process.env[value.slice(1)];
  if (v === undefined) throw new BhError(`${what}: environment variable ${value.slice(1)} is not set`);
  return v;
}

export function loadConfig(ws) {
  const raw = readJson(join(ws, CONFIG_FILE));
  if (!raw.url) throw new BhError(`${CONFIG_FILE}: "url" is required (where the app runs)`);
  const abs = (p) => (p ? resolve(ws, p) : null);
  const prefix = raw.prefix || (raw.name || 'BUG').replace(/[^A-Za-z]/g, '').slice(0, 2).toUpperCase() || 'BH';
  if (!/^[A-Z][A-Z0-9]*$/.test(prefix)) throw new BhError(`${CONFIG_FILE}: "prefix" must be capital letters, e.g. "AL"`);
  return {
    ...raw,
    name: raw.name || 'app',
    prefix,
    environment: raw.environment || 'local',
    url: raw.url.replace(/\/$/, ''),
    source: abs(raw.source),
    spec: Array.isArray(raw.spec) ? raw.spec.map(abs) : raw.spec ? [abs(raw.spec)] : [],
    db: raw.db ? { ...raw.db, file: abs(raw.db.file) } : null,
    app: raw.app ? { ...raw.app, cwd: abs(raw.app.cwd || '.') } : null,
    minutes: raw.minutes || 20,
    ws,
  };
}

export function account(cfg, role) {
  const a = cfg.accounts?.[role];
  if (!a) throw new BhError(`no account for role "${role}" in ${CONFIG_FILE} (roles: ${Object.keys(cfg.accounts || {}).join(', ') || 'none'})`);
  return { role, user: secret(a.user, `${role} user`), password: secret(a.password, `${role} password`) };
}

// The shim lets specs and repro scripts anywhere import the helpers with `import … from '../bh.mjs'`,
// so the workspace needs no node_modules of its own.
export function writeShim(ws) {
  const target = pathToFileURL(join(PKG, 'lib', 'bh.mjs')).href;
  writeFileSync(join(ws, 'bh.mjs'), `// Generated by bughunterr: specs and repro scripts import their helpers from here.\nexport * from '${target}';\n`);
}

export function ensureWorkspace(ws) {
  for (const d of DIRS) mkdirSync(join(ws, d), { recursive: true });
  writeShim(ws);
}

export function bugIds(ws) {
  return listDir(join(ws, 'bugs'), (f) => f.endsWith('.json')).map((f) => f.slice(0, -5));
}

export function nextBugNumber(ws, prefix) {
  const nums = bugIds(ws).filter((id) => id.startsWith(prefix + '-')).map((id) => Number(id.split('-')[1]) || 0);
  return Math.max(0, ...nums) + 1;
}

export function runIdNow(mode) {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}-${mode}`;
}

export const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);
